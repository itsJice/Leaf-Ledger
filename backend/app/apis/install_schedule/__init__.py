"""TBDG Install Schedule — authenticated delivery of the scheduling tool.

The tool is a self-contained HTML page generated by the scheduling pipeline
(tbdg-christmas-schedule/build_review.py syncs it into backend/protected/).
It contains client names, home addresses and phone numbers, so it must NOT
live in the frontend's public/ tree where static hosting would serve it to
anyone with the URL. This router returns it only to a signed-in user —
main.py attaches the Supabase-JWT auth dependency to every /api router.
"""
import pathlib

from fastapi import APIRouter, HTTPException
from fastapi.responses import HTMLResponse

router = APIRouter(prefix="/install-schedule")

BASE = pathlib.Path(__file__).resolve().parents[3] / "protected" / "install-schedule"
ALLOWED = {"index.html", "map.html"}


@router.get("/page", response_class=HTMLResponse)
def get_install_schedule_page(file: str = "index.html") -> str:
    if file not in ALLOWED:
        raise HTTPException(status_code=404, detail="Unknown page")
    path = BASE / file
    if not path.is_file():
        raise HTTPException(
            status_code=404,
            detail="Schedule not generated yet — run the scheduling pipeline",
        )
    return path.read_text(encoding="utf-8")
