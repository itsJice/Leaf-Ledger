"""TBDG Install Schedule — authenticated delivery of the scheduling tool.

The tool is a self-contained HTML page generated by the scheduling pipeline
(scheduler/build_review.py). It contains client names, home addresses,
phone numbers and install dates baked directly into its embedded data, so
it must NOT be a file in the git repo (private or not — see
scheduler/RULES.md) or the frontend's public/ tree, either of which would
expose it to anyone with repo or URL access. It lives in Postgres instead,
pushed there directly by scheduler/publish_pages.py (never committed, never
baked into the deploy image), and this router serves it only to a
signed-in user — main.py attaches the Supabase-JWT auth dependency to
every /api router.

It also stores the reschedule state (which stop sits on which crew-day,
plus approvals). That state is deliberately SHARED, not per-user: several
staff work through client reschedule requests over the same season, and a
per-user document would let two people silently diverge with no merge. It
is keyed on the schedule build version instead, so state saved against an
older build is never applied to a regenerated schedule by accident.

Storage follows the `preferences` router's convention: an app-owned table
in the `ll_app` schema, a jsonb document, and a `FOR UPDATE` read-
modify-write so concurrent saves serialise rather than both landing on the
same stale snapshot.
"""
import json
import os
from typing import Any

import asyncpg
from fastapi import APIRouter, Body, HTTPException, Request
from fastapi.responses import HTMLResponse

from app.apis.user_context import get_request_user_id

router = APIRouter(prefix="/install-schedule")

ALLOWED = {"index.html", "map.html"}

#: One shared document per schedule build. Not a user id — see the module
#: docstring.
MAX_DOC_BYTES = 2_000_000


@router.get("/page", response_class=HTMLResponse)
async def get_install_schedule_page(file: str = "index.html") -> str:
    if file not in ALLOWED:
        raise HTTPException(status_code=404, detail="Unknown page")
    try:
        conn = await get_conn()
    except Exception as exc:
        raise HTTPException(
            status_code=503, detail="Schedule storage unavailable"
        ) from exc
    try:
        await ensure_schema(conn)
        row = await conn.fetchrow(
            "SELECT html FROM ll_app.install_schedule_pages WHERE name = $1", file
        )
    finally:
        await conn.close()
    if not row:
        raise HTTPException(
            status_code=404,
            detail="Schedule not published yet — run scheduler/publish_pages.py",
        )
    return row["html"]


# ─── Shared reschedule state ─────────────────────────────────────────────────


async def get_conn():
    return await asyncpg.connect(
        os.environ.get("DATABASE_URL"), statement_cache_size=0
    )


_SCHEMA_READY = False

#: Keep at most this many history rows per schedule version -- an append-
#: only log with no cap would grow forever across a season of frequent
#: small saves (the tool debounces to one save per 600ms of inactivity,
#: but that's still potentially hundreds of saves over several weeks).
MAX_HISTORY_PER_VERSION = 200

DDL = """
CREATE SCHEMA IF NOT EXISTS ll_app;

-- The compiled tool itself (client names, addresses, phone numbers baked
-- into its embedded data) -- deliberately NOT a file in the git repo or
-- the deploy image (see the module docstring). scheduler/publish_pages.py
-- pushes a fresh build here directly; this endpoint just serves whatever
-- row is current.
CREATE TABLE IF NOT EXISTS ll_app.install_schedule_pages (
    name       text PRIMARY KEY,
    html       text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ll_app.install_schedule_state (
    version    text PRIMARY KEY,
    state      jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_by text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Append-only save history, so several staff working the same schedule can
-- see who changed what and roll back a mistake -- the same shape as a
-- Google Doc's version history. Restoring an old version does not delete
-- anything from this table; it just writes a new current state (and a new
-- history row) that happens to match the old one, so the trail stays intact.
CREATE TABLE IF NOT EXISTS ll_app.install_schedule_history (
    id         bigserial PRIMARY KEY,
    version    text NOT NULL,
    state      jsonb NOT NULL,
    updated_by text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS install_schedule_history_version_idx
    ON ll_app.install_schedule_history (version, created_at DESC);
"""


async def ensure_schema(conn):
    global _SCHEMA_READY
    if _SCHEMA_READY:
        return
    await conn.execute(DDL)
    _SCHEMA_READY = True


def _loads(raw: Any) -> Any:
    """json.loads that returns None rather than raising. asyncpg may hand back
    a decoded object or the raw jsonb text depending on codecs."""
    if raw is None or isinstance(raw, (dict, list)):
        return raw
    if not isinstance(raw, str):
        return None
    try:
        return json.loads(raw)
    except ValueError:
        return None


def _clean_version(version: str) -> str:
    v = (version or "").strip()
    if not v or len(v) > 64 or not v.replace("-", "").replace("_", "").isalnum():
        raise HTTPException(status_code=400, detail="Bad schedule version")
    return v


@router.get("/state")
async def get_state(version: str) -> dict:
    """Current shared state for a schedule build.

    Never 404s on a missing row: no state yet is the normal case on a fresh
    build, and the tool must fall back to its own baseline rather than show
    an error. A storage outage degrades the same way — the tool keeps
    working from localStorage.
    """
    v = _clean_version(version)
    try:
        conn = await get_conn()
    except Exception:
        return {"version": v, "state": None, "storage": "unavailable"}
    try:
        await ensure_schema(conn)
        row = await conn.fetchrow(
            "SELECT state, updated_by, updated_at "
            "FROM ll_app.install_schedule_state WHERE version = $1",
            v,
        )
    finally:
        await conn.close()
    if not row:
        return {"version": v, "state": None}
    return {
        "version": v,
        "state": _loads(row["state"]),
        "updatedBy": row["updated_by"],
        "updatedAt": row["updated_at"].isoformat() if row["updated_at"] else None,
    }


# Leaf & Ledger is the source of truth for whether a client is installing, so a
# removal made in the scheduler has to reach the client record -- not stay in
# this tool's own state where the Clients tab never sees it. Before this, a
# client pulled from the season still had a 2026 client_activity row reading
# "Scheduled 2026-11-25", which is what the Clients tab showed and what the
# scheduler's own popup contradicted.
#
# summarize() in scheduler/sync_clients.py builds that summary from `detail`,
# and `detail` keeps the whole original record -- install_date, total, fees. So
# marking is reversible: set the flag and rewrite the summary, and putting a
# client back can rebuild the original line from what is still there.
NOT_INSTALLING_SUMMARY = "Not installing this year"


def _restored_summary(detail: dict, season: str) -> str:
    """Rebuild what summarize() would have produced, from the kept detail."""
    bits = []
    if detail.get("install_date"):
        bits.append(f"Scheduled {detail['install_date']}")
    else:
        bits.append(f"{season} season")
    total = detail.get("total")
    if total is None and detail.get("install_fee") is not None:
        total = round((detail.get("install_fee") or 0)
                      + (detail.get("takedown_fee") or 0)
                      + (detail.get("storage_fee") or 0), 2)
    if total:
        bits.append(f"${float(total):,.0f}")
    return " · ".join(bits)


async def _reconcile_not_installing(conn, season: str, names: list[str]) -> dict:
    """Make client_activity agree with the scheduler about who is installing.

    Idempotent and narrow: it only ever touches this season's christmas_install
    rows, and only the ones whose flag disagrees with `names`. Both directions
    are handled, so putting a client back restores the line rather than leaving
    a permanent "not installing" behind.
    """
    wanted = {n.strip().lower() for n in names if isinstance(n, str) and n.strip()}
    rows = await conn.fetch(
        "SELECT ca.id, ca.summary, ca.detail, cl.name, "
        "       COALESCE((ca.detail->>'not_installing')::boolean, false) AS flagged "
        "  FROM client_activity ca JOIN clients cl ON cl.id = ca.client_id "
        " WHERE ca.season = $1 AND ca.kind = 'christmas_install'",
        season,
    )
    marked = cleared = 0
    for r in rows:
        is_wanted = (r["name"] or "").strip().lower() in wanted
        if is_wanted == r["flagged"]:
            continue  # already agrees -- most rows, most saves
        detail = _loads(r["detail"]) or {}
        if not isinstance(detail, dict):
            detail = {}
        if is_wanted:
            detail["not_installing"] = True
            summary = NOT_INSTALLING_SUMMARY
            marked += 1
        else:
            detail.pop("not_installing", None)
            summary = _restored_summary(detail, season)
            cleared += 1
        await conn.execute(
            "UPDATE client_activity SET summary = $2, detail = $3::jsonb, updated_at = now() "
            " WHERE id = $1",
            r["id"], summary, json.dumps(detail, default=str),
        )
    return {"marked": marked, "cleared": cleared}


@router.put("/state")
async def put_state(request: Request, body: Any = Body(default=None)) -> dict:
    """Replace the shared state for one schedule build.

    Whole-document write rather than a deep merge: the payload is a single
    placement snapshot ({row -> day}), and merging two snapshots key by key
    would produce a schedule neither person actually approved. The row lock
    serialises concurrent saves, and the response reports who last wrote so
    the tool can tell the user their view was superseded.
    """
    if not isinstance(body, dict):
        raise HTTPException(status_code=400, detail="Body must be an object")
    v = _clean_version(str(body.get("version") or ""))
    state = body.get("state")
    if not isinstance(state, dict):
        raise HTTPException(status_code=400, detail="state must be an object")
    encoded = json.dumps(state)
    if len(encoded) > MAX_DOC_BYTES:
        raise HTTPException(status_code=413, detail="State document too large")

    user_id = get_request_user_id(request)
    try:
        conn = await get_conn()
    except Exception as exc:
        raise HTTPException(
            status_code=503, detail="Schedule state storage unavailable"
        ) from exc
    try:
        await ensure_schema(conn)
        async with conn.transaction():
            await conn.execute(
                "INSERT INTO ll_app.install_schedule_state (version, state, updated_by) "
                "VALUES ($1, '{}'::jsonb, $2) ON CONFLICT (version) DO NOTHING",
                v,
                user_id,
            )
            await conn.fetchval(
                "SELECT state FROM ll_app.install_schedule_state "
                "WHERE version = $1 FOR UPDATE",
                v,
            )
            await conn.execute(
                "UPDATE ll_app.install_schedule_state "
                "SET state = $2::jsonb, updated_by = $3, updated_at = now() "
                "WHERE version = $1",
                v,
                encoded,
                user_id,
            )
            # Append to history, then trim to the retention cap -- every
            # save gets a row, restoring an old one included, so the trail
            # itself is never rewritten.
            await conn.execute(
                "INSERT INTO ll_app.install_schedule_history (version, state, updated_by) "
                "VALUES ($1, $2::jsonb, $3)",
                v,
                encoded,
                user_id,
            )
            await conn.execute(
                "DELETE FROM ll_app.install_schedule_history "
                "WHERE version = $1 AND id NOT IN ("
                "  SELECT id FROM ll_app.install_schedule_history "
                "  WHERE version = $1 ORDER BY created_at DESC LIMIT $2"
                ")",
                v,
                MAX_HISTORY_PER_VERSION,
            )
            # Write the not-installing decision through to the client record,
            # inside the same transaction as the state save so the two cannot
            # disagree if one half fails.
            #
            # Keyed on the field being PRESENT, not on it being non-empty: a
            # page cached from before this shipped sends no such key, and
            # treating that as "nobody is excluded" would clear every flag the
            # newer clients had set. Absent means "this client has nothing to
            # say", which is different from "the list is empty".
            if "notInstallingNames" in state:
                names = state.get("notInstallingNames") or []
                season = str(state.get("season") or "").strip()
                if season.isdigit() and isinstance(names, list):
                    try:
                        await _reconcile_not_installing(conn, season, names)
                    except Exception as exc:  # noqa: BLE001
                        # The schedule save is the user's actual action and must
                        # not fail because the write-through did; the next save
                        # reconciles again from scratch.
                        print(f"not-installing write-through skipped: {exc}")
    finally:
        await conn.close()
    return {"version": v, "ok": True, "updatedBy": user_id}


@router.get("/history")
async def list_history(version: str, limit: int = 50) -> dict:
    """Lightweight save history for a schedule build -- timestamp and who,
    not the full state (kept small; fetch one entry's state on demand to
    preview or restore it). Newest first, like a Google Doc's version list.
    """
    v = _clean_version(version)
    limit = max(1, min(limit, MAX_HISTORY_PER_VERSION))
    try:
        conn = await get_conn()
    except Exception:
        return {"version": v, "entries": [], "storage": "unavailable"}
    try:
        await ensure_schema(conn)
        rows = await conn.fetch(
            "SELECT id, updated_by, created_at FROM ll_app.install_schedule_history "
            "WHERE version = $1 ORDER BY created_at DESC LIMIT $2",
            v,
            limit,
        )
    finally:
        await conn.close()
    return {
        "version": v,
        "entries": [
            {
                "id": r["id"],
                "updatedBy": r["updated_by"],
                "createdAt": r["created_at"].isoformat() if r["created_at"] else None,
            }
            for r in rows
        ],
    }


@router.get("/history/{entry_id}")
async def get_history_entry(entry_id: int, version: str) -> dict:
    """One historical save's full state, for previewing or restoring it.
    Scoped to `version` too so an id from a different (e.g. regenerated)
    schedule build can't be replayed onto this one."""
    v = _clean_version(version)
    try:
        conn = await get_conn()
    except Exception as exc:
        raise HTTPException(
            status_code=503, detail="Schedule state storage unavailable"
        ) from exc
    try:
        await ensure_schema(conn)
        row = await conn.fetchrow(
            "SELECT id, state, updated_by, created_at "
            "FROM ll_app.install_schedule_history WHERE id = $1 AND version = $2",
            entry_id,
            v,
        )
    finally:
        await conn.close()
    if not row:
        raise HTTPException(status_code=404, detail="History entry not found")
    return {
        "id": row["id"],
        "version": v,
        "state": _loads(row["state"]),
        "updatedBy": row["updated_by"],
        "createdAt": row["created_at"].isoformat() if row["created_at"] else None,
    }
